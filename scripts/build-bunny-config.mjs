#!/usr/bin/env node
// Regenerate js/bunny-config.js from Bunny Stream — the single source of truth.
// ---------------------------------------------------------------------------
// Pulls every video in the public Website library and writes a small data file
// that the Plyr initializer (js/bunny-embeds.js) consumes at runtime:
//
//   window.JM_BUNNY_CONFIG = {
//     cdn: "vz-xxxx.b-cdn.net",
//     videos: { "<guid>": { videoId, title, poster, captions, chapters:[{time,label}] } }
//   }
//
// Captions are NOT stored here — the player fetches the VTT live from Bunny's
// CDN (…/<guid>/captions/<lang>.vtt). Only the *presence* of an "en" caption is
// recorded so the player knows whether to attach a track. Chapters are recorded
// because Bunny exposes them only inside its private iframe HTML (no clean public
// endpoint), so a generated mirror is the robust alternative to runtime scraping.
//
// Usage (future video uploads need nothing more than re-running this):
//   set -a; source ~/.ai-secrets/business.env; set +a
//   node scripts/build-bunny-config.mjs            # writes js/bunny-config.js
//   node scripts/build-bunny-config.mjs --check    # verify in sync, exit 1 if not
//
// Then commit js/bunny-config.js. No per-video custom code is ever needed.

import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const LIB = process.env.BUNNY_WEBSITE_LIBRARY_ID;
const KEY = process.env.BUNNY_WEBSITE_STREAM_API_KEY;
const ACCOUNT_KEY = process.env.BUNNY_ACCOUNT_API_KEY; // for the CDN hostname
if (!LIB || !KEY) {
  console.error('Missing BUNNY_WEBSITE_LIBRARY_ID / BUNNY_WEBSITE_STREAM_API_KEY.');
  console.error('Run: set -a; source ~/.ai-secrets/business.env; set +a');
  process.exit(2);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'js', 'bunny-config.js');

async function jget(url, headers) {
  const r = await fetch(url, { headers: { accept: 'application/json', ...headers } });
  if (!r.ok) throw new Error(`${r.status} ${r.statusText} for ${url}`);
  return r.json();
}

// The public playback hostname for this library (vz-xxxx.b-cdn.net).
async function resolveCdnHost() {
  // Prefer the account API (authoritative); fall back to the known host.
  if (ACCOUNT_KEY) {
    try {
      const lib = await jget(`https://api.bunny.net/videolibrary/${LIB}`, { AccessKey: ACCOUNT_KEY });
      const host =
        lib.PullZone && (lib.PullZoneHostName || (lib.PullZoneName && `${lib.PullZoneName}.b-cdn.net`));
      if (host) return host;
      // Some accounts return the CDN host directly:
      if (lib.PullZoneHostName) return lib.PullZoneHostName;
    } catch (e) {
      console.warn('Could not resolve CDN host via account API:', e.message);
    }
  }
  return 'vz-9047a62b-75b.b-cdn.net'; // known host for the Website library (674511)
}

async function main() {
  const check = process.argv.includes('--check');
  const cdn = await resolveCdnHost();

  const data = await jget(
    `https://video.bunnycdn.com/library/${LIB}/videos?page=1&itemsPerPage=100`,
    { AccessKey: KEY },
  );
  const items = data.items || [];
  if (!items.length) throw new Error('No videos returned from the Website library.');

  const videos = {};
  for (const v of items.sort((a, b) => (a.title || '').localeCompare(b.title || ''))) {
    const caps = v.captions || [];
    const hasEn = caps.some((c) => (c.srclang || '').toLowerCase() === 'en');
    const chapters = (v.chapters || [])
      .slice()
      .sort((a, b) => a.start - b.start)
      .map((c) => ({ time: c.start, label: c.title }));
    videos[v.guid] = {
      videoId: v.guid, // overwritten below if a Wistia-style id is known
      title: v.title || '',
      poster: v.thumbnailFileName || null,
      captions: hasEn ? 'en' : null,
      chapters,
    };
  }

  // Map Bunny guid -> original Wistia hashed_id (the tracking video_id), if the
  // migration manifest is present. New videos with no mapping default to guid.
  const mapPath = join(root, '..', 'tmp', 'wistia-bunny-migration', 'manifests', 'website_map.json');
  if (existsSync(mapPath)) {
    try {
      const wmap = JSON.parse(readFileSync(mapPath, 'utf8'));
      for (const [vid, o] of Object.entries(wmap)) {
        if (o.guid && videos[o.guid]) videos[o.guid].videoId = vid;
      }
    } catch (e) {
      console.warn('website_map.json present but unreadable:', e.message);
    }
  }

  const header =
    '// GENERATED by scripts/build-bunny-config.mjs — do not edit by hand.\n' +
    '// Re-run after uploading/changing videos: node scripts/build-bunny-config.mjs\n' +
    '// Bunny is the source of truth; captions are fetched live (not stored here).\n';
  const body =
    'window.JM_BUNNY_CONFIG = ' +
    JSON.stringify({ cdn, videos }, null, 2) +
    ';\n';
  const out = header + body;

  if (check) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur.trim() !== out.trim()) {
      console.error('js/bunny-config.js is OUT OF SYNC with Bunny. Run without --check to update.');
      process.exit(1);
    }
    console.log(`In sync — ${Object.keys(videos).length} videos.`);
    return;
  }

  writeFileSync(OUT, out);
  const chaptered = Object.values(videos).filter((v) => v.chapters.length).length;
  console.log(`Wrote ${OUT}`);
  console.log(`  cdn: ${cdn}`);
  console.log(`  videos: ${Object.keys(videos).length} (${chaptered} chaptered, ` +
    `${Object.values(videos).filter((v) => v.captions).length} with en captions)`);
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
